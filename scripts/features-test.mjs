import { _electron as electron, expect } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import assert from 'node:assert/strict';
const execute = promisify(execFile);
const profile = path.resolve('.cache', `features-profile-${Date.now()}`);
await mkdir(profile, { recursive: true }); await mkdir('test-results', { recursive: true });
const app = await electron.launch({ args: ['.'], env: { ...process.env, SYNCIT_TEST_MODE: '1', SYNCIT_TEST_PROFILE: profile, SYNCIT_TEST_PORT: '22227' } });
const cli = async (...args) => JSON.parse((await execute(process.execPath, [path.resolve('scripts/syncit.mjs'), '--profile', profile, ...args], { windowsHide: true })).stdout);
try {
  const page = await app.firstWindow();
  await expect(page.getByRole('button', { name: 'Create collection' })).toBeVisible();
  await page.getByRole('button', { name: 'Create collection' }).click();
  await expect.poll(() => cli('status').then(status => status.sync.state), { timeout: 20000 }).toBe('unpaired');
  const commands = await cli('commands'); assert.ok(commands.includes('saveNote') && commands.includes('window') && commands.includes('quit'));
  const note = await cli('capture', 'CLI created a multiline prompt\n\nKeep this locally.');
  assert.equal((await cli('read', note.path)).text, note.text);
  await cli('favorite', note.path, 'on');
  await page.getByRole('button', { name: /^Favorites/ }).click();
  await expect(page.locator('[data-testid="item-card"]')).toHaveCount(1);
  await page.keyboard.press('Control+k');
  await expect(page.getByRole('dialog', { name: 'Command palette' })).toBeVisible();
  await page.getByRole('combobox', { name: 'Search commands and files' }).fill('minimal');
  await page.keyboard.press('Enter');
  await expect.poll(async () => (await app.windows()).length).toBe(2);
  const panel = (await app.windows()).find(window => window !== page);
  await expect(panel.getByLabel('Expand floating window')).toBeVisible();
  let status = await cli('status');
  assert.equal(status.panelMode, 'mini'); assert.ok(status.windows.find(w => w.name === 'panel').bounds.height <= 250);
  await panel.getByLabel('Quick capture text').fill('A thought from the tiny window');
  await panel.getByLabel('Save quick capture').click();
  await expect(panel.getByLabel('Quick capture text')).toHaveValue('');
  await expect.poll(() => cli('list', 'tiny window').then(result => result.items.length)).toBe(1);
  await panel.screenshot({ path: path.resolve('test-results/minimal-window.png') });
  assert.equal(await panel.evaluate(() => document.documentElement.scrollHeight <= innerHeight), true, 'Minimal window must fit without clipping');
  await cli('window', 'right');
  await cli('settings', JSON.stringify({ panelOpacity: .85, alwaysOnTop: true }));
  status = await cli('status'); assert.ok(Math.abs(status.windows.find(w => w.name === 'panel').opacity - .85) < .02);
  await cli('window', 'quick');
  await expect(panel.getByRole('heading', { name: 'Latest' })).toBeVisible();
  await panel.getByLabel('Pasteboard text').fill('Text stays after hiding');
  await expect.poll(() => cli('call', 'list', '[]').then(result => result.pasteboard?.text || '')).toBe('Text stays after hiding');
  await cli('window', 'hide');
  assert.equal((await cli('status')).windows.find(w => w.name === 'panel').visible, false);
  await cli('window', 'quick');
  await expect(panel.getByLabel('Pasteboard text')).toHaveValue('Text stays after hiding');
  await panel.getByLabel('Pasteboard text').fill('');
  await cli('settings', JSON.stringify({ panelOpacity: 1 }));
  await panel.screenshot({ path: path.resolve('test-results/floating-workspace.png') });
  const shot = await cli('screenshot', 'panel'); assert.ok((await readFile(shot.path)).length > 100);
  await cli('call', 'saveNote', JSON.stringify([note.path, 'Edited through CLI', note.revision]));
  assert.equal((await cli('read', note.path)).text, 'Edited through CLI');
  const renamed = await cli('call', 'rename', JSON.stringify([note.path, 'Favorite renamed.md']));
  assert.ok((await cli('call', 'initial', '[]')).settings.favorites.includes(renamed));
  await cli('call', 'place', JSON.stringify([{ version: 1, path: renamed, x: 20, y: 40, width: 250, height: 230, updatedAt: Date.now() }]));
  assert.equal((await cli('list')).placements[0].x, 20);
  const file = path.resolve('.cache', `features-import-${Date.now()}.txt`); await writeFile(file, 'CLI import'); await cli('import', file);
  assert.equal((await cli('read', path.basename(file))).text, 'CLI import');
  await cli('pause'); await expect.poll(() => cli('status').then(s => s.sync.state)).toBe('paused'); await cli('resume');
  await cli('settings', JSON.stringify({ panelAutoHide: true })); await cli('window', 'dashboard');
  await expect.poll(() => cli('status').then(s => s.windows.find(w => w.name === 'panel').visible)).toBe(false);
  await cli('settings', JSON.stringify({ panelAutoHide: false }));
  console.log('Six-feature test passed: minimal/quick windows, dock/opacity/autohide, capture/draft, palette, favorites/rename, authenticated CLI notes/import/layout/sync/screenshot.');
} finally { await app.close(); }
